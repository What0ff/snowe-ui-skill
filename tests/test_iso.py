    def test_rounded_surfaces_and_cylinders_take_the_end_point(self):
        route = route_of(tech(box("b", 0, 0, w=2, d=2, radius=0.6), box("a", 5, 0, w=2, d=2),
                              link("a", "b", from_side="x-", to_side="x+", to_offset=0.8, end="dot")))
