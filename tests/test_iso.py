class ConnectorTests(unittest.TestCase):
    def route(self, *objects: dict, **connector) -> dict:
        data = iso.normalize_scene(scene(*objects, {"type": "connector", **connector}))
        items = data["items"]
        solids = [item for item in items if item["type"] not in ("connector", "ground-grid")]
        errors: list[str] = []
        result = iso._connector(iso.Projection(), items[-1], {item["id"]: item for item in solids}, solids, errors)
        self.assertEqual([], errors)
        return result

    def assert_axis_aligned(self, points: list[tuple[float, float]]) -> None:
        for a, b in zip(points, points[1:]):
            self.assertTrue(math.isclose(a[0], b[0], abs_tol=1e-9) != math.isclose(a[1], b[1], abs_tol=1e-9),
                            f"segment {a} -> {b} is not axis-aligned")

    def test_routes_stay_on_grid_axes(self):
        a, b = box("a", 0, 0, w=2, d=2), box("b", 6, 5, w=2, d=2)
        for options in ({}, {"from_side": "y+", "to_side": "x-"}, {"from_side": "x+", "to_side": "x-", "from_offset": 0.5},
                        {"via": [[4, -1], [4, 3]]}, {"from_side": "y+", "to_side": "y-"}):
            with self.subTest(options=options):
                result = self.route(a, b, **{"from": "a", "to": "b", **options})
                self.assert_axis_aligned(result["points"])
                self.assertGreaterEqual(len(result["points"]), 2)

    def test_facing_sides_that_overlap_route_straight(self):
        result = self.route(box("a", 0, 0, w=2, d=2), box("b", 5, 0.5, w=1, d=1), **{"from": "a", "to": "b"})
        self.assertEqual(2, len(result["points"]))
        self.assertAlmostEqual(result["points"][0][1], 1.0)

    def test_connector_is_one_path_with_unit_length_and_end_marker(self):
        svg, _ = iso.render(scene(box("a", 0, 0), box("b", 3, 0), {"type": "connector", "from": "a", "to": "b", "start": "dot"}))
        link = [group for group in groups(svg) if group.get("data-kind") == "connector"][0]
        paths = [child for child in link if child.tag == SVG + "path"]
        self.assertEqual("1", paths[0].get("pathLength"))
        self.assertEqual(["iso-path", "iso-end", "iso-end iso-arrow"], [path.get("class") for path in paths])
        self.assertEqual("iso-a-to-b", link.get("id"))
        self.assertEqual("iso-b", link.get("data-to"))


class RefusalTests(unittest.TestCase):
    def assert_refused(self, data: dict, fragment: str) -> None:
        with self.assertRaises(iso.SceneError) as caught:
            iso.render(data)
        self.assertTrue(any(fragment in error for error in caught.exception.errors),
                        f"{fragment!r} not in {caught.exception.errors}")

    def test_intersecting_volumes(self):
        self.assert_refused(scene(box("a", 0, 0, w=2, d=2), box("b", 1, 1)), "intersect")
        # Touching faces and stacking are allowed.
        iso.render(scene(box("a", 0, 0), box("b", 1, 0), box("c", 0, 0, z=1)))

    def test_chip_pins_count_toward_the_volume(self):
        chip = {"id": "c", "type": "chip", "x": 0, "y": 0, "w": 2, "d": 2}
        self.assert_refused(scene(chip, box("b", 2.1, 0)), "intersect")
        iso.render(scene(dict(chip, pins=0), box("b", 2.1, 0)))

    def test_unknown_type_and_fields(self):
        self.assert_refused(scene({"id": "a", "type": "sphere", "x": 0, "y": 0}), "type must be one of")
        self.assert_refused(scene({"id": "a", "type": ["box"], "x": 0, "y": 0}), "type must be one of")
        self.assert_refused(scene(box("a", 0, 0, colour="red")), "unknown field 'colour'")
        self.assert_refused(dict(scene(box("a", 0, 0)), theme="dark"), "unknown field 'theme'")
        self.assert_refused(scene(box("a", 0, 0), colors={"glow": "#fff"}), "unknown color role")

    def test_missing_and_mistyped_fields(self):
        self.assert_refused(scene({"id": "a", "type": "box", "x": 0, "y": 0, "w": 1, "d": 1}), "missing required field 'h'")
        self.assert_refused(scene(box("a", 0, 0, w="1")), "must be a number")
        self.assert_refused(scene(box("a", 0, 0, w=True)), "must be a number")
        self.assert_refused(scene(box("a", 0, 0, bands=1.5)), "must be an integer")
        self.assert_refused(scene(box("a", 0, 0, accent="yes")), "must be true or false")
        self.assert_refused(scene(box("A", 0, 0)), "lowercase token")
        self.assert_refused(scene(box("a", 0, 0), box("a", 3, 0)), "duplicate id 'a'")
        self.assert_refused(scene(box("a", 0, 0), colors={"top": "white"}), "#rgb or #rrggbb")
        self.assert_refused(scene({"id": "c", "type": "card", "x": 0, "y": 0, "w": 1, "orient": "x+"}), "requires 'h'")
        self.assert_refused(scene({"id": "c", "type": "card", "x": 0, "y": 0, "w": 1, "d": 1, "h": 1}), "does not take 'h'")
        self.assert_refused({"objects": []}, "non-empty list")

    def test_out_of_range_and_non_finite_numbers(self):
        self.assert_refused(scene(box("a", 0, 0, w=0)), "must be in (0, 60]")
        self.assert_refused(scene(box("a", 0, 0, w=-1)), "must be in (0, 60]")
        self.assert_refused(scene(box("a", 500, 0)), "must be in [-100, 100]")
        self.assert_refused(scene(box("a", 0, 0, z=-1)), "must be in [0, 60]")
        self.assert_refused(scene(box("a", 0, 0, w=2, d=2, radius=1.5)), "at most half the shorter side")
        self.assert_refused(scene(box("a", 0, 0), unit=4), "must be in [8, 96]")
        self.assert_refused(scene(box("a", 0, 0, w=float("nan"))), "must be finite")
        self.assert_refused(scene(box("a", 0, 0, w=float("inf"))), "must be finite")
        self.assert_refused(scene(box("a", 0, 0, w=10 ** 400)), "out of range")
        self.assert_refused(scene(box("a", 0, 0), box("b", 3, 0), {"type": "connector", "from": "a", "to": "b", "via": [[10 ** 400, 0]]}),
                            "finite numbers")

    def test_text_limits(self):
        self.assert_refused(scene(box("a", 0, 0, label="x" * 41)), "at most 40 characters")
        self.assert_refused(scene(box("a", 0, 0, label="two\nlines")), "control characters")
        self.assert_refused(scene(box("a", 0, 0, label=" padded")), "surrounding spaces")

    def test_oversized_scenes(self):
        many = [box(f"b{i}", (i % 15) * 2, (i // 15) * 2, w=0.5, d=0.5, h=0.5) for i in range(201)]
        self.assert_refused(scene(*many), "the limit is 200")
        self.assert_refused(scene(box("a", -100, -100), box("b", 99, 99), unit=96), "per side")
        self.assert_refused(scene({"id": "g", "type": "ground-grid", "x": 0, "y": 0, "w": 60, "d": 60, "step": 0.25}), "grid lines exceed")
        labels = [box(f"b{i}-{row}", i * 2, row * 3, w=1, d=1, label="x" * 40) for row in range(3) for i in range(34)]
        self.assert_refused(scene(*labels), "characters of text exceed")

    def test_connector_refusals(self):
        a, b = box("a", 0, 0), box("b", 4, 0)
        self.assert_refused(scene(a, b, {"type": "connector", "from": "a", "to": "nope"}), "unknown object 'nope'")
        self.assert_refused(scene(a, b, box("wall", 2, -1, w=1, d=3), {"type": "connector", "from": "a", "to": "b"}),
                            "passes through 'wall'")
        self.assert_refused(scene(a, b, {"type": "connector", "from": "a", "to": "b", "from_side": "x-"}), "backwards")
