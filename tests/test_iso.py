def scene(*objects: dict, **settings) -> dict:
    return {**settings, "objects": list(objects)}


def box(identifier: str, x: float, y: float, z: float = 0, w: float = 1, d: float = 1, h: float = 1, **extra) -> dict:
    return {"id": identifier, "type": "box", "x": x, "y": y, "z": z, "w": w, "d": d, "h": h, **extra}


def groups(svg_text: str) -> list[ET.Element]:
    return [element for element in ET.fromstring(svg_text) if element.tag == SVG + "g"]


def path_points(d: str) -> list[tuple[float, float]]:
    """Endpoints of every M, L and A command in a path generated by iso.py."""
    points = []
    for command, body in re.findall(r"([MLAZ])([^MLAZ]*)", d):
        numbers = [float(value) for value in body.split()]
        if command in "ML":
            points.append((numbers[0], numbers[1]))
        elif command == "A":
            points.append((numbers[5], numbers[6]))
    return points


def luminance(hex_color: str) -> float:
    channels = [int(hex_color[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


class ProjectionTests(unittest.TestCase):
    def test_isometric_axes_have_equal_length_at_thirty_degrees(self):
        proj = iso.Projection("isometric", 32)
        x_axis, y_axis, z_axis = proj.vec(1, 0, 0), proj.vec(0, 1, 0), proj.vec(0, 0, 1)
        self.assertAlmostEqual(x_axis[0], 32 * math.cos(math.radians(30)), places=9)
        self.assertAlmostEqual(x_axis[1], 32 * math.sin(math.radians(30)), places=9)
        self.assertAlmostEqual(y_axis[0], -x_axis[0], places=9)
        self.assertAlmostEqual(y_axis[1], x_axis[1], places=9)
        self.assertAlmostEqual(z_axis[0], 0.0, places=9)
        self.assertAlmostEqual(z_axis[1], -32.0, places=9)
        for axis in (x_axis, y_axis, z_axis):
            self.assertAlmostEqual(math.hypot(*axis), 32.0, places=9)

    def test_dimetric_ground_axes_rise_one_in_two(self):
        proj = iso.Projection("dimetric", 20)
        x_axis = proj.vec(1, 0, 0)
        self.assertAlmostEqual(x_axis[1] / x_axis[0], 0.5, places=12)
        self.assertAlmostEqual(math.hypot(*x_axis), 20.0, places=9)
        # An orthographic camera at 30 degrees elevation stretches the vertical axis.
        self.assertAlmostEqual(-proj.vec(0, 0, 1)[1] / 20.0, math.cos(math.radians(30)) / math.sqrt(0.625), places=9)

    def test_projection_is_linear_and_view_direction_collapses(self):
        proj = iso.Projection("isometric", 24)
        a, b = proj(1.5, -2, 3), proj(0.5, 4, 1)
        total = proj(2, 2, 4)
        self.assertAlmostEqual(total[0], a[0] + b[0], places=9)
        self.assertAlmostEqual(total[1], a[1] + b[1], places=9)
        for kind in ("isometric", "dimetric"):
            proj = iso.Projection(kind, 32)
            collapsed = proj.vec(*proj.view)
            self.assertAlmostEqual(collapsed[0], 0.0, places=9)
            self.assertAlmostEqual(collapsed[1], 0.0, places=9)
        self.assertEqual(iso.project(1, 0, 0, "isometric", 10), iso.Projection("isometric", 10)(1, 0, 0))


class ShadingTests(unittest.TestCase):
    def test_box_faces_paint_right_then_left_then_top_then_outline(self):
        svg, _ = iso.render(scene(box("a", 0, 0, w=2, d=1, h=1)))
        group = groups(svg)[0]
        self.assertEqual(["iso-r", "iso-l", "iso-t", "iso-o"], [path.get("class") for path in group])

    def test_visible_faces_sit_where_the_fixed_light_direction_puts_them(self):
        svg, _ = iso.render(scene(box("a", 0, 0, w=2, d=1, h=1)))
        hull, left, top, _ = groups(svg)[0]
        hull_x = [x for x, _ in path_points(hull.get("d"))]
        left_points = path_points(left.get("d"))
        top_y = [y for _, y in path_points(top.get("d"))]
        # The left face ends at the front crease; the right face (hull remainder) extends past it.
        crease_x = max(x for x, _ in left_points)
        self.assertGreater(max(hull_x), crease_x + 10)
        self.assertLess(min(x for x, _ in left_points), crease_x - 10)
        # The top face is the highest region on screen.
        self.assertLessEqual(min(top_y), min(y for _, y in left_points))

    def test_fallback_tones_follow_top_left_right_lightness(self):
        for style in ("line", "solid"):
            colors = iso.DEFAULT_COLORS[style]
            self.assertGreater(luminance(colors["top"]), luminance(colors["left"]))
            self.assertGreater(luminance(colors["left"]), luminance(colors["right"]))

    def test_upright_card_shades_its_cap_by_its_facing_axis(self):
        svg, _ = iso.render(scene({"id": "c", "type": "card", "x": 0, "y": 0, "w": 2, "h": 1, "orient": "x+"}))
        classes = [path.get("class") for path in groups(svg)[0]]
        self.assertEqual(["iso-l", "iso-t", "iso-r", "iso-o"], classes[:4])

    def test_outline_is_thicker_than_detail(self):
        svg, _ = iso.render(scene(box("a", 0, 0)))
        style = ET.fromstring(svg).find(SVG + "style").text
        outline = float(re.search(r"\.iso-o\{[^}]*stroke-width:([\d.]+)", style).group(1))
        detail = float(re.search(r"\.iso-d\{[^}]*stroke-width:([\d.]+)", style).group(1))
        self.assertGreater(outline, detail)
        self.assertIn("vector-effect:non-scaling-stroke", style)


class DepthOrderTests(unittest.TestCase):
    def paint_order(self, data: dict) -> list[str]:
        _, manifest = iso.render(data)
        return [element["source_id"] for element in manifest["elements"]]

    def test_front_object_paints_after_back_object_regardless_of_declaration(self):
        front = box("front", 2, 0, w=1, d=3, h=2)
        back = box("back", 0, 0, w=2, d=3, h=3)
        self.assertEqual(["back", "front"], self.paint_order(scene(front, back)))
        self.assertEqual(["back", "front"], self.paint_order(scene(back, front)))

    def test_overlapping_footprints_order_along_each_axis(self):
        low = box("low", 0, 0, w=2, d=2, h=1)
        on_top = box("on-top", 0, 0, z=1, w=2, d=2, h=1)
        beside = box("beside", 0, 2, w=2, d=1, h=3)
        order = self.paint_order(scene(beside, on_top, low))
        self.assertLess(order.index("low"), order.index("on-top"))
        self.assertLess(order.index("low"), order.index("beside"))
        self.assertLess(order.index("on-top"), order.index("beside"))

    def test_tall_back_object_still_paints_before_short_front_object(self):
        tower = box("tower", 0, 0, w=1, d=1, h=8)
        step = box("step", 1, 1, w=1, d=1, h=0.2)
        self.assertEqual(["tower", "step"], self.paint_order(scene(step, tower)))

    def test_ground_connector_paints_before_objects_it_passes_behind(self):
        data = scene(
            box("a", 0, 0, w=1, d=1, h=1), box("b", 4, 0, w=1, d=1, h=1), box("wall", 2, -2, w=1, d=1.5, h=3),
            {"type": "connector", "from": "a", "to": "b"},
        )
        order = self.paint_order(data)
        self.assertLess(order.index("a-to-b"), order.index("b"))

    def test_cyclic_occlusion_is_refused(self):
        data = scene(box("a", 0, 1, z=3, w=4, d=3, h=4), box("b", 4, 1, z=1, w=3, d=1, h=4), box("c", 3, 3, w=4, d=4, h=3))
        with self.assertRaises(iso.SceneError) as caught:
            iso.render(data)
        self.assertIn("cyclic occlusion", str(caught.exception))


class DeterminismAndStructureTests(unittest.TestCase):
    def test_last_bit_differences_round_identically_across_platforms(self):
        # macOS and Linux libm can differ in the last bit of sin/cos; values on a rounding
        # boundary must still format identically (CI once saw 379.68 versus 379.69).
        for boundary in (379.685, 153.245, -12.335, 0.005, 1024.995):
            values = [boundary]
            for _ in range(4):
                values.append(math.nextafter(values[-1], math.inf))
            down = boundary
            for _ in range(4):
                down = math.nextafter(down, -math.inf)
                values.append(down)
            self.assertEqual(1, len({iso._fmt(value) for value in values}), boundary)

    def test_identical_input_gives_identical_bytes(self):
        data = json.loads((EXAMPLES / "agent-hub.scene.json").read_text(encoding="utf-8"))
        first = iso.render(json.loads(json.dumps(data)))
        second = iso.render(json.loads(json.dumps(data)))
        self.assertEqual(first[0].encode("utf-8"), second[0].encode("utf-8"))
        self.assertEqual(json.dumps(first[1]), json.dumps(second[1]))

    def test_committed_examples_match_the_current_generator(self):
        for source in sorted(EXAMPLES.glob("*.scene.json")):
            name = source.name[: -len(".scene.json")]
            with self.subTest(scene=name):
                svg, manifest = iso.render_file(source)
                self.assertEqual((EXAMPLES / f"{name}.svg").read_text(encoding="utf-8"), svg)
                committed = json.loads((EXAMPLES / f"{name}.manifest.json").read_text(encoding="utf-8"))
                self.assertEqual(committed, json.loads(json.dumps(manifest)))
                self.assertEqual([], manifest["warnings"])

    def test_svg_is_well_formed_self_contained_and_sized(self):
        svg, manifest = iso.render_file(EXAMPLES / "data-platform.scene.json")
        root = ET.fromstring(svg)
        self.assertEqual(SVG + "svg", root.tag)
        self.assertEqual(f"0 0 {manifest['width']} {manifest['height']}", root.get("viewBox"))
        self.assertEqual(str(manifest["width"]), root.get("width"))
        lowered = svg.lower()
        for forbidden in ("href", "url(", "http:", "https:", "<script", "<image", "@import", "<foreignobject"):
            self.assertNotIn(forbidden, lowered.replace("http://www.w3.org/2000/svg", ""))
        self.assertTrue(svg.endswith("</svg>\n"))
        self.assertNotIn("\r", svg)

    def test_every_object_and_connector_has_stable_hooks(self):
        svg, manifest = iso.render_file(EXAMPLES / "data-platform.scene.json")
        dom = groups(svg)
        self.assertEqual([element["id"] for element in manifest["elements"]], [group.get("id") for group in dom])
        for group, element in zip(dom, manifest["elements"]):
            self.assertTrue(group.get("id").startswith("dp-"))
            self.assertIn(f"iso-{element['kind']}", group.get("class").split())
            self.assertEqual(element["role"], group.get("data-role"))
            self.assertEqual(str(element["paint"]), group.get("data-paint"))
            if element["order"] is not None:
                self.assertEqual(str(element["order"]), group.get("data-order"))
            bbox = element["bbox"]
            self.assertGreaterEqual(bbox["x"], 0)
            self.assertGreaterEqual(bbox["y"], 0)
            self.assertLessEqual(bbox["x"] + bbox["width"], manifest["width"])
            self.assertLessEqual(bbox["y"] + bbox["height"], manifest["height"])
            if element["kind"] == "connector":
                paths = [child for child in group if child.get("pathLength")]
                self.assertEqual(1, len(paths))
                self.assertEqual("1", paths[0].get("pathLength"))
                self.assertEqual(element["path"], paths[0].get("id"))
                self.assertEqual(element["from"], group.get("data-from"))
                self.assertGreater(element["length"], 0)

    def test_title_makes_an_image_and_no_title_makes_it_decorative(self):
        titled, _ = iso.render(scene(box("a", 0, 0), title="Ingest tier", desc="One box"))
        root = ET.fromstring(titled)
        self.assertEqual("img", root.get("role"))
        self.assertEqual("iso-title iso-desc", root.get("aria-labelledby"))
        self.assertEqual("Ingest tier", root.find(SVG + "title").text)
        plain, _ = iso.render(scene(box("a", 0, 0)))
        root = ET.fromstring(plain)
        self.assertEqual("true", root.get("aria-hidden"))
        self.assertIsNone(root.get("role"))


class ColorTests(unittest.TestCase):
    def test_every_paint_comes_from_a_custom_property_with_a_fallback(self):
        svg, _ = iso.render_file(EXAMPLES / "agent-hub.scene.json")
        root = ET.fromstring(svg)
        style = root.find(SVG + "style").text
        for prop, value in re.findall(r"(fill|stroke):([^;}]+)", style):
            if value == "none":
                continue
            with self.subTest(prop=prop, value=value):
                self.assertRegex(value, r"^(?:var\(--iso-[a-z]+,#[0-9a-f]{6}\)|color-mix\(in srgb,var\(--iso-accent,#[0-9a-f]{6}\) \d+%,var\(--iso-[a-z]+,#[0-9a-f]{6}\)\))$")
        for role in ("top", "left", "right", "stroke", "detail", "accent", "text"):
            self.assertIn(f"var(--iso-{role},", style)
        self.assertIn("var(--iso-font,", style)
        for element in root.iter():
            for attribute in ("fill", "stroke", "style", "color", "stop-color"):
                self.assertIsNone(element.get(attribute), f"{element.tag} carries a raw {attribute}")

    def test_scene_colors_replace_fallbacks_only(self):
        svg, _ = iso.render(scene(box("a", 0, 0), colors={"accent": "#FF5500", "top": "#fafafa"}))
        self.assertIn("var(--iso-accent,#ff5500)", svg)
        self.assertIn("var(--iso-top,#fafafa)", svg)
        self.assertIn(f"var(--iso-right,{iso.DEFAULT_COLORS['line']['right']})", svg)


